# Regenerate `src/translate/psy5_units_generated.jl`: the PSY5 fields stored per unit on the
# component's own base, read from PowerSystems 5's struct descriptors (`needs_conversion`).
#
#   julia --project=scripts/psy5_units -e 'using Pkg; Pkg.instantiate()'
#   julia --project=scripts/psy5_units scripts/psy5_units/generate_psy5_units.jl
#
# The updater never depends on PowerSystems; this script is how it learns PSY5's storage
# conventions anyway. Fields PSY5 stores some other way and never annotated (system-base per
# unit, fractions, natural units) are listed by hand in `PSY5_STORAGE`
# (`src/translate/units.jl`), not here.

using PowerSystems
import JSON

const DESCRIPTORS =
    joinpath(pkgdir(PowerSystems), "src", "descriptors", "power_system_structs.json")
const OUTPUT = normpath(
    joinpath(@__DIR__, "..", "..", "src", "translate", "psy5_units_generated.jl"),
)

function device_base_fields()
    structs = JSON.parsefile(DESCRIPTORS)["auto_generated_structs"]
    fields = Pair{Tuple{String, String}, String}[]
    for s in structs, f in s["fields"]
        if get(f, "needs_conversion", false) == true
            unit = lstrip(string(get(f, "conversion_unit", "")), ':')
            push!(fields, (String(s["struct_name"]), String(f["name"])) => unit)
        end
    end
    sort!(fields; by = first)
    return fields
end

function main()
    fields = device_base_fields()
    open(OUTPUT, "w") do io
        println(io,
            "# Generated by scripts/psy5_units/generate_psy5_units.jl from PowerSystems ",
            pkgversion(PowerSystems), "'s")
        println(
            io,
            "# src/descriptors/power_system_structs.json. Do not edit; rerun the script.",
        )
        println(io, "#! format: off")
        println(io)
        println(io, "\"\"\"")
        println(
            io,
            "PSY5 fields stored per unit on the component's own `base_power` (the system base for a",
        )
        println(
            io,
            "component with none): every field PSY5's descriptors mark `needs_conversion`, as",
        )
        println(
            io,
            "`(type, field) => conversion_unit`. The unit names the physical quantity PSY5's getters",
        )
        println(io, "convert it to (`mva` for power, `ohm` for impedance, ...).")
        println(io, "\"\"\"")
        println(io, "const PSY5_DEVICE_BASE_FIELDS = Dict{Tuple{String, String}, String}(")
        for ((type, field), unit) in fields
            println(io, "    (", repr(type), ", ", repr(field), ") => ", repr(unit), ",")
        end
        println(io, ")")
        println(io, "#! format: on")
    end
    println("wrote ", length(fields), " fields to ", OUTPUT)
end

main()
